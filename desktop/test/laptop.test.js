// Run with: node test/laptop.test.js
const assert = require("assert");
const fs = require("fs");
const os = require("os");
const path = require("path");
const laptop = require("../laptop");

(async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "ocean-test-"));
  const allowed = path.join(root, "Clients");
  const secret = path.join(root, "Private");
  fs.mkdirSync(path.join(allowed, "posh"), { recursive: true });
  fs.mkdirSync(secret);
  fs.writeFileSync(path.join(allowed, "posh", "brief.txt"), "Budget R15000");
  fs.writeFileSync(path.join(secret, "bank.txt"), "secret");
  fs.writeFileSync(path.join(allowed, "photo.png"), Buffer.from([0x89, 0x50, 0, 0, 1]));
  fs.symlinkSync(secret, path.join(allowed, "sneaky"));
  const shell = { openPath: async () => "", openExternal: async () => {} };
  const yes = async () => true;
  const no = async () => false;
  const run = (name, args, confirm = yes, folders = [allowed]) => laptop.run({ name, arguments: args }, { folders, confirm, shell });

  let r = await run("read_file", { path: "posh/brief.txt" });
  assert(r.ok && r.message.includes("Budget R15000"), "reads inside");
  r = await run("read_file", { path: path.join(secret, "bank.txt") });
  assert(!r.ok && r.message.includes("outside"), "refuses absolute outside");
  r = await run("read_file", { path: "../Private/bank.txt" });
  assert(!r.ok, "refuses .. escape");
  r = await run("read_file", { path: "sneaky/bank.txt" });
  assert(!r.ok && r.message.includes("outside"), "refuses symlink escape");
  r = await run("read_file", { path: "photo.png" });
  assert(!r.ok && r.message.includes("not a text file"), "refuses binary");
  r = await run("write_file", { path: "posh/new.md", content: "hi" }, no);
  assert(!r.ok && !fs.existsSync(path.join(allowed, "posh", "new.md")), "write needs approval");
  r = await run("write_file", { path: "posh/new.md", content: "hi" });
  assert(r.ok && fs.readFileSync(path.join(allowed, "posh", "new.md"), "utf8") === "hi", "writes when approved");
  r = await run("write_file", { path: "posh/new.md", content: "again" });
  assert(!r.ok && r.message.includes("already exists"), "no silent overwrite");
  r = await run("write_file", { path: "posh/new.md", content: "again", overwrite: true });
  assert(r.ok, "overwrite when asked and approved");
  r = await run("write_file", { path: path.join(secret, "x.txt"), content: "x" });
  assert(!r.ok && !fs.existsSync(path.join(secret, "x.txt")), "no writes outside");
  r = await run("write_file", { path: "sneaky/x.txt", content: "x" });
  assert(!r.ok && !fs.existsSync(path.join(secret, "x.txt")), "no writes through symlink");
  r = await run("list_folder", { path: "" });
  assert(r.ok && r.message.includes(allowed), "lists allowed folders");
  r = await run("list_folder", { path: "posh" });
  assert(r.ok && r.message.includes("brief.txt"), "lists folder");
  r = await run("find_files", { name: "brief" });
  assert(r.ok && r.message.includes("brief.txt") && !r.message.includes("bank"), "finds files");
  r = await run("read_file", { path: "posh/brief.txt" }, yes, []);
  assert(!r.ok && r.message.includes("No folders"), "nothing allowed by default");
  r = await run("open_link", { url: "file:///etc/passwd" });
  assert(!r.ok, "only web links");
  r = await run("delete_file", { path: "posh/brief.txt" });
  assert(!r.ok && fs.existsSync(path.join(allowed, "posh", "brief.txt")), "no delete action");
  r = await run("claude_code", { folder: "posh", task: "Build it" }, no);
  assert(!r.ok, "Claude Code needs approval");
  console.log("All laptop tests passed.");
})().catch((e) => { console.error(e); process.exit(1); });
